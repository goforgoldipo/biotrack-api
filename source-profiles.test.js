describe("profile definitions", () => {
  const SAME_AS = ["", "weight", "bodyFat", "fatMass", "leanMass", "muscleMass", "boneMass", "bmi", "bmr", "restingHR", "vo2max", "hrv", "spo2", "respiratoryRate", "bloodPressureSystolic", "bloodPressureDiastolic"];
  test.each(SP.PROFILES.map(p => [p.id, p]))("%s: valid fields and section", (_id, p) => {
    const labels = p.fields.map(f => f.label.toLowerCase());
    expect(new Set(labels).size).toBe(labels.length);
    for (const f of p.fields) {
      expect(SAME_AS).toContain(f.sameAs);
      expect(["up", "down", "neutral"]).toContain(f.direction);
    }
    const def = SP.sectionDef(p);
    expect(def.name).toBe(p.section);
    for (const k of def.kpis) expect(["sum", "avg", "last"]).toContain(k.aggregate);
  });
  test("profiles of one app share one section, and shared labels keep the same unit", () => {
    const byApp = {};
    for (const p of SP.PROFILES) (byApp[p.app] ||= new Set()).add(p.section);
    for (const s of Object.values(byApp)) expect(s.size).toBe(1);
    const unitOf = {};
    for (const p of SP.PROFILES) for (const f of p.fields) {
      const k = `${p.section}|${f.label}`;
      if (unitOf[k] != null) expect(f.unit).toBe(unitOf[k]); else unitOf[k] = f.unit;
    }
  });
  test("semicolon normalizer keeps quoted commas and fixes decimal commas", () => {
    const { headers, records } = parseCSVText(SP.normalizeDelimiter(`"a";"b";"c"\n"1,5";"x, y";"2"`));
    expect(headers).toEqual(["a", "b", "c"]);
    expect(records[0]).toEqual({ a: "1.5", b: "x, y", c: "2" });
    expect(SP.normalizeDelimiter("a,b\n1;2,3")).toBe("a,b\n1;2,3");
  });
});
