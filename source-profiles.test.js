describe("detection", () => {
  test("every profile has a sample", () => {
    expect(Object.keys(S).sort()).toEqual(SP.PROFILES.map(p => p.id).sort());
  });
  test.each(Object.keys(S))("%s sample matches exactly that one profile", (id) => {
    expect(SP.matchAll(S[id], parseCSVText).map(p => p.id)).toEqual([id]);
    expect(SP.detect(S[id], parseCSVText).id).toBe(id);
  });
  test("MFP nutrition with the newer Time column still matches", () => {
    const t = S.mfp_nutrition.replace("Date,Meal,", "Date,Meal,Time,").split("\n").map((l, i) => i ? l.replace(/^([^,]+,[^,]+,)/, "$108:00,") : l).join("\n");
    expect(SP.matchAll(t, parseCSVText).map(p => p.id)).toEqual(["mfp_nutrition"]);
    expect(day(run("mfp_nutrition", t), "2026-11-01").Calories).toBe(2000);
  });
  test("Withings weight.csv in lb matches and is not converted", () => {
    const t = S.withings_weight.replace(/\(kg\)/g, "(lb)");
    expect(SP.detect(t, parseCSVText).id).toBe("withings_weight");
    expect(day(run("withings_weight", t), "2026-06-08").Weight).toBeCloseTo(81);
  });
  test("Hevy imperial layout matches", () => {
    const t = S.hevy_workouts.replace('"weight_kg"', '"weight_lbs"').replace('"distance_km"', '"distance_miles"');
    expect(SP.detect(t, parseCSVText).id).toBe("hevy_workouts");
    expect(day(run("hevy_workouts", t), "2025-01-30")["Heaviest set"]).toBe(80);
  });
  test("unknown files match nothing", () => {
    expect(SP.detect("Date,Steps\n2026-01-01,1000", parseCSVText)).toBeNull();
    expect(SP.detect("Date,Exercise,Reps,Weight(kg),Duration(s),Distance(m),Incline,Resistance,isWarmup,Note,multiplier\n2026-05-06 10:27:01 +0000,Squat, 5, 100,0,0,0,0,false,,1", parseCSVText)).toBeNull();
  });
});

